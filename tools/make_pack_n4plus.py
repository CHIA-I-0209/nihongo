# 產生 data/pack-n4plus.json：N4 文法補充（10 項）
# 例句格式：{漢字|かな} 振假名、[[p:を]] 助詞挖空、[[g:答案|提示]] 文法挖空
import json, os

G = []  # (編號, 文法名稱, 接續, 意思, 說明, JLPT)
S = []  # (編號, 文法編號, 日文, 中文)

def g(n, title, pattern, meaning, expl, jlpt=4):
    G.append((n, title, pattern, meaning, expl, jlpt))

def s(gn, jp, zh):
    S.append((len(S) + 1, gn, jp, zh))

g(1, '～ようです（推測）', '普通形 ＋ ようです（名詞 ＋ の、な形容詞 ＋ な）', '好像…、似乎…',
  '根據看到、聽到、感覺到的狀況做判斷，比「みたい」正式。名詞要加「の」：留守のようです；な形容詞要加「な」：静かなようです。')
s(1, '{外|そと}は{寒|さむ}い[[g:ようです|好像]]。', '外面好像很冷。')
s(1, '{田中|たなか}さんは{留守|るす}[[g:のようです|好像]]。', '田中先生好像不在家。')

g(2, '～ことができます', '動詞辭書形 ＋ ことができます', '能夠…、會…、可以…',
  '表示能力或可能性，比可能形正式。名詞也可以直接接「ができます」：日本語ができます。')
s(2, '{私|わたし}は{漢字|かんじ}を{書|か}く[[g:ことができます|能夠]]。', '我會寫漢字。')
s(2, 'ここで{写真|しゃしん}を[[g:{撮|と}ることができます|撮る]]。', '這裡可以拍照。')

g(3, '～つもりです', '動詞辭書形／ない形 ＋ つもりです', '打算…',
  '表示已經想好的打算。「〜ないつもりです」是打算不做。語氣比「〜ようと思います」更確定。')
s(3, '{夏休|なつやす}みに{国|くに}へ[[g:{帰|かえ}るつもりです|帰る]]。', '暑假打算回國。')
s(3, 'もうタバコは[[g:{吸|す}わないつもりです|吸う]]。', '我打算不再抽菸了。')

g(4, '～予定です', '動詞辭書形／名詞の ＋ 予定です', '預定…',
  '表示已經安排好的行程，比「つもり」更客觀、確定，常用於工作和行程。')
s(4, '{来月|らいげつ}{大阪|おおさか}へ{出張|しゅっちょう}する[[g:{予定|よてい}です|預定]]。', '下個月預定去大阪出差。')
s(4, '{会議|かいぎ}は{三時|さんじ}から[[g:の{予定|よてい}です|預定]]。', '會議預定從三點開始。')

g(5, '～てみます', '動詞て形 ＋ みます', '試著…看看',
  '表示嘗試做某件事、看看結果如何。過去式「〜てみました」很常用。')
s(5, 'この{服|ふく}を[[g:{着|き}てみます|着る]]。', '試穿這件衣服看看。')
s(5, '{日本|にほん}の{料理|りょうり}を[[g:{作|つく}ってみました|作る]]。', '試著做了日本料理。')

g(6, '～ようになります', '動詞辭書形／可能形 ＋ ようになります', '變得會…、開始…',
  '表示能力或習慣的變化，常用過去式「〜ようになりました」。變得不再做是「〜なくなりました」。')
s(6, '{日本語|にほんご}が[[g:{話|はな}せるようになりました|話す]]。', '我變得會說日語了。')
s(6, '{毎朝|まいあさ}{運動|うんどう}[[g:するようになりました|する]]。', '我開始每天早上運動了。')

g(7, '～ことにします', '動詞辭書形／ない形 ＋ ことにします', '決定…',
  '表示自己做的決定。「〜ことにしました」是已經決定了；「〜ことになりました」則是別人或情況決定的。')
s(7, '{毎日|まいにち}{日記|にっき}を[[g:{書|か}くことにしました|書く]]。', '我決定每天寫日記。')
s(7, '{今日|きょう}はお{酒|さけ}を[[g:{飲|の}まないことにします|飲む]]。', '今天決定不喝酒。')

g(8, '～のに（逆接）', '普通形 ＋ のに（名詞・な形容詞 ＋ なのに）', '明明…卻…',
  '結果和預期相反，帶有不滿、遺憾或意外的語氣。後面不能接請求或命令。')
s(8, 'たくさん{勉強|べんきょう}した[[g:のに|明明]]、{試験|しけん}に{落|お}ちました。', '明明很用功，考試卻沒過。')
s(8, '{日曜日|にちようび}な[[g:のに|明明]]、{会社|かいしゃ}へ{行|い}きました。', '明明是星期天，卻去了公司。')

g(9, '～し（列舉理由）', '普通形 ＋ し、普通形 ＋ し', '而且…、又…',
  '列舉兩個以上的理由或特點，常暗示還有其他理由。')
s(9, 'この{店|みせ}は{安|やす}い[[g:し|而且]]、おいしいです。', '這家店又便宜又好吃。')
s(9, '{雨|あめ}も{降|ふ}っている[[g:し|而且]]、{今日|きょう}は{出|で}かけません。', '又在下雨，今天就不出門了。')

g(10, '～ために（目的・原因）', '動詞辭書形／名詞の ＋ ために', '為了…；因為…',
  '表示目的時，前面接自己能控制的動作（辭書形）或「名詞＋の」。也可以表示原因，語氣比較正式。')
s(10, '{日本|にほん}へ{行|い}く[[g:ために|為了]]、お{金|かね}を{貯|た}めています。', '為了去日本，正在存錢。')
s(10, '{家族|かぞく}[[g:のために|為了]]{働|はたら}きます。', '為了家人工作。')
s(10, '{事故|じこ}の[[g:ために|因為]]、{電車|でんしゃ}が{遅|おく}れました。', '因為事故，電車誤點了。')

pack = {
    'grammar': [{'id': f'gc{n:02d}', 'title': t, 'pattern': p, 'meaning': m, 'explanation': e, 'jlpt': j} for n, t, p, m, e, j in G],
    'sentences': [{'id': f'sc{n:02d}', 'jp': jp, 'zh': zh, 'words': '', 'grammar': f'gc{gn:02d}'} for n, gn, jp, zh in S],
}
out = os.path.join(os.path.dirname(__file__), '..', 'data', 'pack-n4plus.json')
json.dump(pack, open(out, 'w'), ensure_ascii=False, indent=2)
print(len(pack['grammar']), 'grammar,', len(pack['sentences']), 'sentences')
